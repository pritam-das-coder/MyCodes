# Demonstrate the use of different operators (arithmetic, logical, and bitwise) by writing a program that takes two integers and outputs the results of &, |, ^, >>, and << operations.

a = int(input("Enter 1st number : "))
b = int(input("Enter 2nd number : "))

print(a & b)
print(a | b)
print(a ^ b)
print(a >> b)
print(a << b)
print(~ a)